import type { TerrainAppearance } from "../core/types";

/*
 * Game content: how each terrain material is drawn. The engine receives it through the scene
 * (`createScene(app, world, modules, { terrain: TERRAIN_APPEARANCE })`).
 */

/** Darkening per level below the highest elevation, for blocks above water. */
const HEIGHT_TINT_STEP = 0.025;

/** Green-yellow light on the top levels of grass and ground. */
const LAND_TOP_TINT = 0xf5ffdc;
/** Color multipliers chosen by broad seeded noise, so neighboring columns share subtle land tones. */
const LAND_NOISE_TINTS = {
  scale: 11,
  colors: [0xffffff, 0xfffbea, 0xf4f9df, 0xf2f5d6],
} as const;
/**
 * Grass zones by broad seeded noise, from the lowest noise to the highest: lush and darker,
 * slightly darker, plain, yellowish and dry yellow. Strong enough to read through the height tint
 * and the day's light grade.
 */
const GRASS_NOISE_TINTS = {
  scale: 10,
  colors: [0xbfd5bd, 0xdde9d4, 0xffffff, 0xfff0c0, 0xffe49c],
} as const;

const GRASS_VARIANT_FRAMES = [
  { chance: 0.05, column: 0, row: 0 },
  { chance: 0.04, column: 1, row: 0 },
  { chance: 0.025, column: 2, row: 0 },
  { chance: 0.025, column: 0, row: 1 },
  { chance: 0.07, column: 1, row: 1 },
  { chance: 0.04, column: 2, row: 1 },
  { chance: 0.035, column: 0, row: 2 },
  { chance: 0.015, column: 1, row: 2 },
  { chance: 0.02, column: 2, row: 2 },
] as const;

/** Side of a frame of the path spritesheet, in source pixels: the canvas of a block. */
const PATH_FRAME = { width: 1024, height: 853 } as const;

/**
 * The sixteen looks of a path block in `path_tiles.svg` (made by `artifacts/path_tiles.py`), by
 * connection mask (`+x` 1, `+y` 2, `−x` 4, `−y` 8): four per row, mask `m` at column `m % 4`, row
 * `⌊m / 4⌋`.
 */
const PATH_FRAMES = Array.from({ length: 16 }, (_, mask) => ({
  x: (mask % 4) * PATH_FRAME.width,
  y: Math.floor(mask / 4) * PATH_FRAME.height,
  ...PATH_FRAME,
}));

/**
 * The terrain materials: grass and ground share the land tint (grass with flowers, sprouts or
 * fallen leaves on some columns), sand keeps its colour, water darkens with depth and has bands of
 * light drifting across it.
 */
export const TERRAIN_APPEARANCE: TerrainAppearance = {
  grass: {
    textureSource: "/assets/grass/block.svg",
    tint: { kind: "height", topTint: LAND_TOP_TINT, step: HEIGHT_TINT_STEP },
    noiseTints: GRASS_NOISE_TINTS,
    // Ground cover uses frames from one shared spritesheet generated by `artifacts/grass_clutter.py`.
    variants: [
      ...GRASS_VARIANT_FRAMES.map(({ chance, column, row }) => ({
        textureSource: "/assets/grass/grass_variants.svg",
        chance,
        frame: { x: column * 1024, y: row * 853, width: 1024, height: 853 },
      })),
    ],
  },
  ground: {
    textureSource: "/assets/ground/block.svg",
    tint: { kind: "height", topTint: LAND_TOP_TINT, step: HEIGHT_TINT_STEP },
    noiseTints: LAND_NOISE_TINTS,
  },
  water: {
    textureSource: "/assets/water/block.svg",
    tint: { kind: "depth", step: 0.15 },
    // Soft light drifting across the water: three bands every two tiles, two tiles in 9 s; under
    // the first level, fainter and slower.
    bands: { count: 3, width: 0.45, alpha: 0.16, period: 9000, deepBelow: -1, deep: 0.45 },
  },
  // A grass block with a strip of trodden earth across its top, joined to the paths around it. Its
  // grass edges take the tint of the grass zone it crosses.
  path: {
    textureSource: "/assets/path/block.svg",
    tint: { kind: "height", topTint: LAND_TOP_TINT, step: HEIGHT_TINT_STEP },
    noiseTints: { ...GRASS_NOISE_TINTS, field: "grass" },
    connections: { textureSource: "/assets/path/path_tiles.svg", frames: PATH_FRAMES },
  },
  // Neutral: the same height darkening as grass, without the green cast. Its top is half a block lower.
  sand: {
    textureSource: "/assets/sand/block.svg",
    tint: { kind: "height", topTint: 0xffffff, step: HEIGHT_TINT_STEP },
    topInset: 0.5,
  },
};
